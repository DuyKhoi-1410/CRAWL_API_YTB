# 3. Tham số cào dữ liệu
MIN_DURATION_SEC = 180        # Bỏ video < 3 phút (Shorts/Teaser)
MAX_COMMENTS_PER_RUN = 3000   # Trần an toàn / video / phiên
LOOKBACK = timedelta(minutes=15)

NOW = datetime.now(timezone.utc)
WINDOW_START = NOW - timedelta(days=14)   # Khung [n-14, n-7) UTC
WINDOW_END = NOW - timedelta(days=7)
INGESTED_AT = NOW.isoformat()
RUN_TS = NOW.strftime("%Y%m%dT%H%M%SZ")

LOCAL_ROOT = "./colab_output"
STATE_PATH = "state/video_state.json"
BRONZE_PREFIX = f"bronze/youtube/run_date={NOW:%Y-%m-%d}/run_ts={RUN_TS}"


class QuotaExceeded(Exception):
    """Hết quota API trong ngày: dừng cào và lưu an toàn."""


class StorageAdapter:
    """Bộ đẩy dữ liệu thô chuyên biệt cho tầng BRONZE (GCS hoặc Local)."""
    def __init__(self):
        self.use_gcs = bool(BUCKET_NAME)
        if self.use_gcs:
            from google.cloud import storage
            self.client = storage.Client()
            self.bucket = self.client.bucket(BUCKET_NAME)

    def _local_path(self, path):
        full = os.path.join(LOCAL_ROOT, path)
        os.makedirs(os.path.dirname(full), exist_ok=True)
        return full

    def read_state(self, path):
        if self.use_gcs:
            blob = self.bucket.blob(path)
            return json.loads(blob.download_as_text(encoding="utf-8")) if blob.exists() else None
        full = os.path.join(LOCAL_ROOT, path)
        if not os.path.exists(full):
            return None
        with open(full, encoding="utf-8") as f:
            return json.load(f)

    def write_raw_jsonl(self, path, rows):
        """Đẩy file .jsonl thô lên Bronze Storage."""
        content = "".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows)
        if self.use_gcs:
            self.bucket.blob(path).upload_from_string(content.encode("utf-8"), content_type="application/x-ndjson")
        else:
            with open(self._local_path(path), "w", encoding="utf-8", newline="\n") as f:
                f.write(content)

    def write_state_json(self, path, obj):
        """Cập nhật file State quản lý tiến trình."""
        content = json.dumps(obj, ensure_ascii=False, indent=2)
        if self.use_gcs:
            self.bucket.blob(path).upload_from_string(content.encode("utf-8"), content_type="application/json")
        else:
            with open(self._local_path(path), "w", encoding="utf-8", newline="\n") as f:
                f.write(content)


