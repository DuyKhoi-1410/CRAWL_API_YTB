def get_api_key():
    key = os.environ.get("YOUTUBE_API_KEY")
    if not key:
        raise RuntimeError(
            "Chưa cấu hình YOUTUBE_API_KEY trong biến môi trường (Environment Variable) hoặc Secret Manager."
        )
    return key.strip()

def parse_iso(ts):
    return datetime.fromisoformat(ts.replace("Z", "+00:00"))

def clean_text(text):
    return text.replace("\n", " ").replace("\r", " ") if text is not None else None

def to_int_or_none(val):
    try: return int(val)
    except (TypeError, ValueError): return None

def parse_duration_to_sec(iso):
    m = re.fullmatch(r"P(?:(\d+)D)?T?(?:(\d+)H)?(?:(\d+)M)?(?:(\d+)S)?", iso or "")
    if not m: return 0
    d, h, mi, s = (int(x or 0) for x in m.groups())
    return d * 86400 + h * 3600 + mi * 60 + s

def execute_api_call(request, retries=3):
    for i in range(retries):
        try:
            return request.execute()
        except HttpError as e:
            try:
                reason = json.loads(e.content.decode("utf-8"))["error"]["errors"][0].get("reason", "unknown")
            except Exception:
                reason = "unknown"

            if reason in ("quotaExceeded", "dailyLimitExceeded"):
                raise QuotaExceeded(reason)

            if (reason in ("rateLimitExceeded", "userRateLimitExceeded") or e.resp.status >= 500) and i < retries - 1:
                time.sleep(2 ** (i + 1))
                continue
            raise

"""## 2. Thu thập dữ liệu video và comment"""

def process_single_video_metadata(item):
    vid = item["id"]
    snip = item.get("snippet", {})
    stats = item.get("statistics", {})
    details = item.get("contentDetails", {})

    duration_sec = parse_duration_to_sec(details.get("duration"))
    if 0 < duration_sec < MIN_DURATION_SEC:
        return vid, None, "skipped_short"

    pub_at = snip.get("publishedAt")
    age_days = round((NOW - parse_iso(pub_at)).total_seconds() / 86400, 2) if pub_at else None

    record = {
        "video_id": vid,
        "channel_id": snip.get("channelId"),
        "channel_title": clean_text(snip.get("channelTitle")),
        "video_title": clean_text(snip.get("title")),
        "program_name": None,
        "video_published_at": pub_at,
        "view_count": to_int_or_none(stats.get("viewCount")),
        "video_like_count": to_int_or_none(stats.get("likeCount")),
        "total_comment_count": to_int_or_none(stats.get("commentCount")),
        "video_age_days": age_days,
        "ingested_at": INGESTED_AT,
        "run_id": RUN_TS,
    }
    return vid, record, "active"


def fetch_raw_comments_page(yt, vid, watermark=None, page_token=None, max_rows=None, stop_before_watermark=False):
    threshold = parse_iso(watermark) - LOOKBACK if watermark and stop_before_watermark else None
    rows, token = [], page_token
    cap = max_rows or MAX_COMMENTS_PER_RUN

    while True:
        resp = execute_api_call(yt.commentThreads().list(
            part="snippet", videoId=vid, maxResults=100, order="time",
            textFormat="plainText", pageToken=token))

        next_token = resp.get("nextPageToken")
        for t in resp.get("items", []):
            cs = t["snippet"]["topLevelComment"]["snippet"]
            published = cs.get("publishedAt")

            if threshold and published and parse_iso(published) < threshold:
                return rows, None, False

            rows.append({
                "comment_id": t["snippet"]["topLevelComment"]["id"],
                "video_id": vid,
                "program_name": None,
                "parent_id": None,
                "channel_id": cs.get("channelId"),
                "author_channel_id": (cs.get("authorChannelId") or {}).get("value"),
                "author_display_name": clean_text(cs.get("authorDisplayName")),
                "raw_text": clean_text(cs.get("textOriginal") or cs.get("textDisplay")),
                "like_count": to_int_or_none(cs.get("likeCount")),
                "reply_count": to_int_or_none(t["snippet"].get("totalReplyCount")),
                "comment_published_at": published,
                "ingested_at": INGESTED_AT,
                "run_id": RUN_TS,
            })
            if len(rows) >= cap:
                return rows, next_token, bool(next_token)

        if not next_token:
            return rows, None, False
        token = next_token


def process_video_comments_ingestion(yt, vid, vs, cbuf):
    if vs.get("comments_disabled"):
        return

    try:
        if not vs.get("watermark"):
            rows, next_page, reached_cap = fetch_raw_comments_page(
                yt, vid, max_rows=MAX_COMMENTS_PER_RUN, stop_before_watermark=False
            )
            cbuf.extend(rows)
            newest = max((r["comment_published_at"] for r in rows if r.get("comment_published_at")), key=parse_iso, default=None)
            if newest:
                vs["watermark"] = newest
            vs["backfill_page_token"] = next_page
            vs["backfill_complete"] = not bool(next_page and reached_cap)
        else:
            rows, _, _ = fetch_raw_comments_page(
                yt, vid, watermark=vs.get("watermark"),
                max_rows=MAX_COMMENTS_PER_RUN, stop_before_watermark=True
            )
            cbuf.extend(rows)
            newest = max((r["comment_published_at"] for r in rows if r.get("comment_published_at")), key=parse_iso, default=None)
            if newest and parse_iso(newest) > parse_iso(vs["watermark"]):
                vs["watermark"] = newest

            if vs.get("backfill_page_token") and not vs.get("backfill_complete"):
                remaining = max(0, MAX_COMMENTS_PER_RUN - len(rows))
                if remaining:
                    older_rows, next_page, reached_cap = fetch_raw_comments_page(
                        yt, vid, page_token=vs["backfill_page_token"],
                        max_rows=remaining, stop_before_watermark=False
                    )
                    cbuf.extend(older_rows)
                    vs["backfill_page_token"] = next_page
                    if not next_page or not reached_cap:
                        vs["backfill_complete"] = True

        print(f"   - {vid}: +{len(rows)} comment thô")
    except HttpError as e:
        try:
            reason = json.loads(e.content.decode("utf-8"))["error"]["errors"][0].get("reason", "")
        except Exception:
            reason = ""
        if reason == "commentsDisabled":
            vs["comments_disabled"] = True
            print(f"   [SKIP] {vid}: comment bị khóa")
        else:
            print(f"   [ERROR] {vid}: {reason}")

"""## 3. ĐẨY DỮ LIỆU LÊN BRONZE"""

def flush_bronze_checkpoint(storage, vbuf, cbuf, state):
    """ĐẨY TOÀN BỘ DỮ LIỆU CỦA ĐỢT CÀO THÀNH 1 FILE DUY NHẤT LÊN GCS."""
    if vbuf or cbuf:
        if vbuf:
            storage.write_raw_jsonl(f"{BRONZE_PREFIX}/video_snapshots/video_snapshots.jsonl", vbuf)
        if cbuf:
            storage.write_raw_jsonl(f"{BRONZE_PREFIX}/comments/comments.jsonl", cbuf)

        print(f"\n✅ [BRONZE SUCCESS] Đã gộp và đẩy thành công +{len(vbuf)} video, +{len(cbuf)} comment thành 1 FILE DUY NHẤT lên GCS!")
        vbuf.clear()
        cbuf.clear()
    else:
        print("\nℹ️ Không có dữ liệu mới phát sinh trong đợt chạy này.")

    storage.write_state_json(STATE_PATH, state)


def run_bronze_pipeline():
    storage = StorageAdapter()
    yt = build("youtube", "v3", developerKey=get_api_key(), cache_discovery=False)
    state = storage.read_state(STATE_PATH) or {"videos": {}}
    state.setdefault("videos", {})

    video_buffer, comment_buffer = [], []

    try:
        # 1. Quét danh sách Video mới từ Kênh
        for channel_id in CHANNELS:
            try:
                items = execute_api_call(yt.channels().list(part="contentDetails", id=channel_id)).get("items")
                if not items: continue
                uploads_id = items[0]["contentDetails"]["relatedPlaylists"]["uploads"]

                token, stop_channel = None, False
                while not stop_channel:
                    resp = execute_api_call(yt.playlistItems().list(
                        part="contentDetails", playlistId=uploads_id, maxResults=50, pageToken=token))

                    for it in resp.get("items", []):
                        pub = it["contentDetails"].get("videoPublishedAt")
                        if not pub or parse_iso(pub) >= WINDOW_END: continue
                        if parse_iso(pub) < WINDOW_START:
                            stop_channel = True
                            break

                        vid = it["contentDetails"]["videoId"]
                        state["videos"].setdefault(vid, {
                            "status": "active", "published_at": pub,
                            "watermark": None, "backfill_page_token": None,
                            "backfill_complete": False
                        })
                    token = resp.get("nextPageToken")
                    if not token: break
            except HttpError as e:
                print(f"[ERROR] Playlist error channel {channel_id}: {e}")

        # 2. Đánh dấu các video cũ hơn 14 ngày
        for v in state["videos"].values():
            if v["status"] == "active" and parse_iso(v["published_at"]) < WINDOW_START:
                v["status"] = "final"

        active_vids = [vid for vid, v in state["videos"].items() if v["status"] == "active"]
        print(f"Tổng số Video đang theo dõi (Active): {len(active_vids)}")

        # 3. Thu thập Video Metadata & Comment dồn toàn bộ vào bộ nhớ
        for i in range(0, len(active_vids), 50):
            chunk = active_vids[i:i + 50]
            try:
                resp = execute_api_call(yt.videos().list(part="snippet,contentDetails,statistics", id=",".join(chunk)))
            except HttpError as e:
                print(f"[ERROR] video list: {e}")
                continue

            returned_vids = set()
            for item in resp.get("items", []):
                vid, record, status = process_single_video_metadata(item)
                returned_vids.add(vid)
                vs = state["videos"][vid]

                if status == "skipped_short":
                    vs["status"] = "skipped_short"
                    continue

                if record:
                    video_buffer.append(record)

                # Dồn toàn bộ comment cào được vào đệm
                process_video_comments_ingestion(yt, vid, vs, comment_buffer)

            for vid in set(chunk) - returned_vids:
                state["videos"][vid]["status"] = "unavailable"

    except QuotaExceeded:
        print("\n⚠️ [STOP] Bị hết Quota API! Đang lưu toàn bộ dữ liệu cào được trước thời điểm bị dừng...")
    finally:
        # LUÔN XẢ TOÀN BỘ DỮ LIỆU ĐÃ CÀO THÀNH 1 FILE DUY NHẤT LÊN GCS KHI KẾT THÚC
        flush_bronze_checkpoint(storage, video_buffer, comment_buffer, state)


if __name__ == "__main__":
    run_bronze_pipeline()